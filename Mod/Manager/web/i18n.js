const LANGS = ["en", "ja", "ko", "zh"];

function pickLang() {
  try {
    const saved = localStorage.getItem("bl-lang");
    if (LANGS.includes(saved)) return saved;
  } catch (e) { /* storage unavailable */ }
  for (const l of navigator.languages || [navigator.language || "en"]) {
    const code = String(l).toLowerCase().slice(0, 2);
    if (LANGS.includes(code)) return code;
  }
  return "en";
}

let LANG = pickLang();
const LOCALE = { en: "en-US", ja: "ja-JP", ko: "ko-KR", zh: "zh-CN" };

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

/* static texts in index.html: data-i18n (text), data-i18n-ph (placeholder), data-i18n-title (title) */
function applyStaticTexts() {
  document.documentElement.lang = LANG;
  document.title = t("html.title");
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}

function setLang(code) {
  if (!LANGS.includes(code)) return;
  LANG = code;
  try { localStorage.setItem("bl-lang", code); } catch (e) { /* ignore */ }
  applyStaticTexts();
}
